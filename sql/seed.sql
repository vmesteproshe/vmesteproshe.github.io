## Деньги: кто за что платит

Не существует единственно правильной схемы. Можно делить аренду пополам, платить пропорционально доходу или складывать общую сумму на бытовые расходы.

Важно не «как принято», а чтобы оба понимали правила и не чувствовали себя должниками.

Обсудите:
- кто платит за аренду и коммунальные услуги;
- как покупается общая мебель и техника;
- нужен ли общий счёт;
- что будет, если один временно потеряет доход.

## Быт: какой порядок считается нормой

Составьте короткий список: посуда, уборка, стирка, готовка, мусор, покупки. Для каждой задачи найдите ответственного.

Если один не замечает беспорядок, а другой не может расслабиться в неубранной комнате, договоритесь о минимальном стандарте. Например: «вечером кухня остаётся пустой».

## Личное время и гости

Договоритесь, сколько времени каждому нужно на восстановление и как вы сообщаете о планах.

Про гостей полезно ответить на три вопроса:
- предупреждаем за сколько часов?
- можно ли приводить друзей без предупреждения?
- где граница личного пространства?

## Конфликты: как вы будете ссориться

Ссоры будут. Вопрос в том, что происходит после. Можно договориться не выяснять отношения ночью, не уходить из дома молча и не использовать прошлые ошибки как аргумент.

> Хорошая договорённость — не та, которая исключает конфликты, а та, которая помогает из них выходить.

Полезно заранее выбрать фразу для паузы: «Мне нужно 20 минут, я вернусь к разговору». Это не избегание, если вы действительно возвращаетесь.

## Как провести разговор

1. Выберите спокойное время, а не вечер после переезда.
2. Обсуждайте по одной теме за раз.
3. Говорите о своих ожиданиях, а не о том, что «все так делают».
4. Запишите решения — память у обоих избирательная.

